# BatchNorm 需要区分训练和推理两个阶段。
# 因为 BatchNorm 是跨样本计算均值和方差的，
# 不同 Batch 的样本组成不同，计算得到的统计量也可能不同。
# 如果推理时仍使用当前 Batch 的统计量，预测结果就可能受到其他样本的影响。
# 因此，训练时使用当前 Batch 的统计量，并通过 EMA 累积运行均值和方差；
# 推理时则直接使用训练过程中保存的运行统计量。

# LayerNorm 和 RMSNorm 都是对每个 Token 独立进行归一化，
# 不依赖其他样本或 Token，因此训练和推理的计算方式一致。

